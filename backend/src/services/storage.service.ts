import fs from 'fs';
import path from 'path';
import { Readable } from 'stream';
import { del, get, put } from '@vercel/blob';
import { ApiError } from '../utils/ApiError';
import { randomToken } from '../utils/helpers';

/**
 * File storage for uploads.
 *
 * - `public`  admin images (hotels, tours, banners), served at /uploads/<name> with long caching.
 * - `private` visa documents, only streamed to their owner or an admin.
 *
 * Locally files go to ./uploads/{public,private}. On Vercel the filesystem is read-only and not
 * persistent, so files go to a **private** Vercel Blob store (both scopes, under `public/` and
 * `private/` prefixes) and are streamed back through the API. Connect a Blob store to the API
 * project with a read-write token (BLOB_READ_WRITE_TOKEN).
 */
export type StorageScope = 'public' | 'private';

const UPLOAD_ROOT = path.resolve(process.cwd(), 'uploads');
const BLOB_TOKEN = process.env.BLOB_READ_WRITE_TOKEN || undefined;
const useBlob = Boolean(BLOB_TOKEN || process.env.BLOB_STORE_ID);
/** Running on Vercel without a Blob store: writes would be lost, so refuse them clearly. */
const noStorage = !useBlob && Boolean(process.env.VERCEL);

export const storageMode = useBlob ? 'vercel-blob' : noStorage ? 'unavailable' : 'local-disk';

const EXTENSIONS: Record<string, string> = {
  'image/jpeg': '.jpg',
  'image/png': '.png',
  'image/webp': '.webp',
  'application/pdf': '.pdf',
};

/** Random, extension-from-MIME name: client filenames are never trusted or reused. */
function storedNameFor(mimeType: string) {
  return `${Date.now()}-${randomToken(12)}${EXTENSIONS[mimeType] ?? ''}`;
}

/** Stored names are generated by us; anything else (paths, traversal) is rejected. */
function safeName(name: string) {
  const base = path.basename(name);
  if (!/^[\w.-]{1,120}$/.test(base) || base !== name) return null;
  return base;
}

function localDir(scope: StorageScope) {
  const dir = path.join(UPLOAD_ROOT, scope);
  fs.mkdirSync(dir, { recursive: true });
  return dir;
}

export async function saveUpload(scope: StorageScope, file: { buffer: Buffer; mimetype: string }): Promise<string> {
  if (noStorage) throw new ApiError(503, 'File uploads are not available: storage is not configured', 'STORAGE_UNAVAILABLE');
  const name = storedNameFor(file.mimetype);
  if (useBlob) {
    await put(`${scope}/${name}`, file.buffer, { access: 'private', contentType: file.mimetype, addRandomSuffix: false, token: BLOB_TOKEN });
  } else {
    await fs.promises.writeFile(path.join(localDir(scope), name), file.buffer);
  }
  return name;
}

export async function openUpload(scope: StorageScope, storedName: string): Promise<{ stream: Readable; contentType: string } | null> {
  const name = safeName(storedName);
  if (!name || noStorage) return null;
  if (useBlob) {
    const result = await get(`${scope}/${name}`, { access: 'private', token: BLOB_TOKEN });
    if (!result || !result.stream) return null;
    return { stream: Readable.fromWeb(result.stream as import('stream/web').ReadableStream), contentType: result.blob.contentType ?? 'application/octet-stream' };
  }
  const filePath = path.join(UPLOAD_ROOT, scope, name);
  if (!fs.existsSync(filePath)) return null;
  const ext = path.extname(name);
  const contentType = Object.entries(EXTENSIONS).find(([, e]) => e === ext)?.[0] ?? 'application/octet-stream';
  return { stream: fs.createReadStream(filePath), contentType };
}

/** Best effort: used to clean up after a request that failed half-way. */
export async function deleteUploads(scope: StorageScope, storedNames: string[]) {
  const names = storedNames.map(safeName).filter((n): n is string => !!n);
  if (!names.length || noStorage) return;
  try {
    if (useBlob) await del(names.map((n) => `${scope}/${n}`), { token: BLOB_TOKEN });
    else await Promise.all(names.map((n) => fs.promises.unlink(path.join(UPLOAD_ROOT, scope, n)).catch(() => undefined)));
  } catch (err) {
    console.error('Upload cleanup failed:', (err as Error).message);
  }
}
